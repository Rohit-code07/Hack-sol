import grievanceApi from '../api/grievanceApi';
import { adaptGrievance } from '../api/adapters';

function getActiveFarmerId() {
  try {
    const raw = localStorage.getItem('ks_auth');
    if (raw) {
      const parsed = JSON.parse(raw);
      if (parsed.farmerId) return parsed.farmerId;
      if (parsed.id) return parsed.id;
    }
  } catch (e) {}
  return null;
}

function resolveFarmerUuid(id) {
  if (!id) return getActiveFarmerId();
  return id;
}

/**
 * Fetch grievance history for a farmer
 */
export async function getGrievances(farmerId) {
  const uuid = resolveFarmerUuid(farmerId);
  if (!uuid) return { success: true, data: [] };
  try {
    const res = await grievanceApi.getByFarmer(uuid);
    const rawList = Array.isArray(res.data) ? res.data : [];
    const adaptedList = rawList.map(adaptGrievance);
    return { success: true, data: adaptedList };
  } catch (err) {
    return { success: true, data: [] };
  }
}

/**
 * Generate official grievance petition in Spring Boot
 */
export async function submitGrievance(params = {}) {
  const {
    farmerId,
    category = 'WRONG_LAND_RECORD',
    subject,
    description = '',
    discrepancyId,
    language = 'hi',
    department,
    bankName,
    branchName,
    relatedRecordReference,
    expectedResolution,
    amountInvolved,
    dateOfIncident,
    transactionId,
    priority = 'MEDIUM',
  } = params;

  const uuid = resolveFarmerUuid(farmerId);
  if (!uuid) throw new Error('No farmer identity found to file grievance');

  try {
    const directRequest = {
      farmerId: uuid,
      discrepancyId: discrepancyId ? Number(discrepancyId) : null,
      subject: subject || `${category.replace(/_/g, ' ')} - Dispute Petition`,
      grievanceContent: description,
      grievanceCategory: category,
      department: department || 'Revenue / Agriculture Department',
      bankName: bankName || null,
      branchName: branchName || null,
      relatedRecordReference: relatedRecordReference || null,
      expectedResolution: expectedResolution || null,
      amountInvolved: amountInvolved ? Number(amountInvolved) : 0,
      dateOfIncident: dateOfIncident || null,
      transactionId: transactionId || null,
      priority,
      language: language === 'en' ? 'en' : 'hi',
    };

    const res = await grievanceApi.submit(directRequest);
    const adapted = adaptGrievance(res.data);
    return { success: true, data: adapted };
  } catch (err) {
    const request = {
      farmerId: uuid,
      discrepancyId: Number(discrepancyId) || 1,
      language: language === 'en' ? 'en' : 'hi',
      additionalNotes: description,
    };

    const res = await grievanceApi.generate(request);
    const adapted = adaptGrievance(res.data);
    return { success: true, data: adapted };
  }
}

/**
 * Download formal grievance PDF generated by Spring Boot (OpenPDF)
 */
export async function downloadGrievancePdf(id, filename) {
  return grievanceApi.downloadPdf(id, filename);
}

export default {
  getGrievances,
  submitGrievance,
  downloadGrievancePdf,
};
